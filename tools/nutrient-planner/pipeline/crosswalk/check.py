#!/usr/bin/env python3
"""Check crosswalk.json against the downloaded tables and write a review report.

For every entry it confirms that the record still exists with the same code AND name,
recomputes the composition flags (see propose.py), and lists what the record would add.
It fails (exit 1) if an 'accept' or 'check' entry points at a record that is missing or
renamed, so a refreshed table can never silently change what a planner food is linked to.

This script changes no planner data. Merging is a separate, later step.

Usage (standard library only):
  python3 -I check.py --db cofid --table PATH.xlsx --usda-zip SR_LEGACY.zip
Writes ../../data/foods/crosswalk_report_<db>.md
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOL = HERE.parents[1]
sys.path.insert(0, str(HERE))
import propose  # noqa: E402
import sources  # noqa: E402

# Nutrients the planner lacks for every USDA food (SR Legacy has no iodine), shown in the report.
GAIN = ["iodine"]
MISSING_CODES = {"Tr": "trace", "N": "N (present, amount unknown)", None: "blank (not analysed)"}


def describe(cell) -> str:
    if cell in MISSING_CODES:
        return MISSING_CODES[cell]
    return propose.fmt(cell)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", required=True, choices=["cofid"])
    ap.add_argument("--table", required=True)
    ap.add_argument("--usda-zip", required=True)
    args = ap.parse_args()

    xwalk = json.loads((HERE / "crosswalk.json").read_text())[args.db]
    foods = {f["id"]: f for f in json.loads((TOOL / "data/foods/foods.json").read_text())["foods"]}
    usda = sources.load_usda_subset(Path(args.usda_zip), {foods[e["food"]]["fdcId"] for e in xwalk})
    table = sources.load_cofid(Path(args.table))

    errors, rows = [], []
    for e in xwalk:
        f = foods.get(e["food"])
        if f is None:
            errors.append(f"{e['food']}: not a planner food")
            continue
        if e["verdict"] == "none":
            rows.append((e, None, []))
            continue
        rec = table.get(f"{e['code']}|{e['name']}")
        if rec is None:
            errors.append(f"{e['food']}: {e['code']} '{e['name']}' not found in the table")
            continue
        u = usda[f["fdcId"]]
        flags = propose.profile_flags(u, rec)
        agree = propose.states_agree(propose.states(set(propose.words(u.name))),
                                     propose.states(set(propose.words(rec.name))))
        if agree is False:
            flags.append("cooking/preservation state differs")
        rows.append((e, rec, flags))

    count = Counter(e["verdict"] for e in xwalk)
    gains = {n: sum(1 for e, r, _ in rows if e["verdict"] == "accept" and r and r.num(n) is not None)
             for n in GAIN}
    lines = [f"# Crosswalk report: {args.db}", "",
             "Generated by `pipeline/crosswalk/check.py` from `pipeline/crosswalk/crosswalk.json`. "
             "Nothing here is used by the planner yet.", "",
             f"Common foods: {len(xwalk)}. Accepted: {count['accept']}; to check: {count['check']}; "
             f"no equivalent: {count['none']}.", ""]
    lines += [f"- Accepted foods with a measured {n} value: {k}" for n, k in gains.items()]
    lines += ["", "| Food | Verdict | Record | " + " | ".join(GAIN) + " | Composition flags | Note |",
              "|---|---|---|" + "---|" * len(GAIN) + "---|---|"]
    for e, rec, flags in rows:
        record = f"{rec.code} {rec.name}" if rec else "–"
        vals = " | ".join(describe(rec.raw.get(n)) if rec else "–" for n in GAIN)
        lines.append(f"| {foods[e['food']]['name']} | {e['verdict']} | {record} | {vals} | "
                     f"{'; '.join(flags) or '–'} | {e['note']} |")
    out = TOOL / f"data/foods/crosswalk_report_{args.db}.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(TOOL)}", file=sys.stderr)
    for err in errors:
        print("ERROR:", err, file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
