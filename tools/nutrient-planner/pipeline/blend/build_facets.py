#!/usr/bin/env python3
"""Write the facet table for each food table the planner uses (step 1 of the blended food list).

For every food in a table's planner file it writes one row: the table's own code and name (as published), the
planner's id, and the facets found by facets.py. Output (generated, don't edit by hand):

  facets/<table>.csv   one row per food; open it in a spreadsheet to review
  facets/REPORT.md     how much of each table the vocabulary describes, conflicts, and the most common
                       unclassified words (where the vocabulary should grow next)

Tables covered now: USDA SR Legacy (every food in the planner, data/foods/foods.json) and CoFID 2021 (every
record, from the archived spreadsheet, fetched and checked by inputs.py). Standard library only:

  python3 -I tools/nutrient-planner/pipeline/blend/build_facets.py
"""
from __future__ import annotations

import collections
import csv
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOL = HERE.parents[1]
sys.path.insert(0, str(HERE))  # explicit, because the script is run with python3 -I
import facets  # noqa: E402

OUT = HERE / "facets"
TAGS = {"usda-sr-legacy": "usda", "cofid-2021": "cofid"}  # FDC ids are unique across all USDA datasets
COLUMNS = ["id", "code", "name", "planner_id", "common", "base", *facets.ORDER, "detail", "rest", "conflicts"]


# Each table: (file name with version, short tag used in permanent ids, title). The tag has no version, so ids
# survive a new release; the version a value came from is recorded with the value.
def usda() -> tuple[str, str, list[dict]]:
    d = json.loads((TOOL / "data/foods/foods.json").read_text())
    rows = [{"code": f["fdcId"], "name": f["usdaName"], "planner_id": f["id"], "common": "yes" if f.get("common") else ""}
            for f in d["foods"]]
    return "usda-sr-legacy", "USDA SR Legacy (FoodData Central, 2018-04)", rows


def cofid() -> tuple[str, str, list[dict]]:
    """Every CoFID 2021 record (not only the planner's selection), so matching can see the whole table. Read from
    the archived spreadsheet (inputs.py checks it)."""
    sys.path.insert(0, str(HERE.parent / "crosswalk"))
    import sources  # noqa: E402
    import inputs  # noqa: E402
    planner = {(f["src"]["code"], f["src"]["name"]): f for f in
               json.loads((TOOL / "data/foods/foods-cofid.json").read_text())["foods"]}
    rows = []
    for rec in sources.load_cofid(inputs.get("cofid-2021")).values():
        f = planner.get((rec.code, rec.name))
        rows.append({"code": rec.code, "name": rec.name, "planner_id": f["id"] if f else "",
                     "common": "yes" if f and f.get("common") else ""})
    return "cofid-2021", "CoFID 2021 (McCance and Widdowson's, every record)", rows


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def with_ids(table: str, rows: list[dict]) -> list[dict]:
    """Permanent food ids: '<table>:<code>'. If a publisher used one code for several foods (CoFID 2021 13-669),
    each of those gets '~' and a short form of its published name, so ids stay unique and readable."""
    counts = collections.Counter(r["code"] for r in rows)
    return [{"id": f"{TAGS[table]}:{r['code']}" + (f"~{slug(r['name'])[:40]}" if counts[r["code"]] > 1 else ""), **r}
            for r in rows]


def main() -> int:
    vocab = facets.load_vocabulary()
    OUT.mkdir(exist_ok=True)
    report = ["# Facet coverage", "",
              "Generated by `build_facets.py`; don't edit. A food is *fully described* when every phrase of its name",
              "was recognised (its `rest` column is empty). Unrecognised phrases are kept, never guessed at, and",
              "matching treats them as differences until a person reviews them.", ""]
    for table, title, rows in (usda(), cofid()):
        words: collections.Counter[str] = collections.Counter()
        conflicts = []
        out = []
        for r in sorted(with_ids(table, rows), key=lambda r: (r["name"].lower(), r["code"])):
            d = facets.describe(r["name"], vocab)
            out.append(r | d.row())
            for p in d.rest:
                words[p] += 1
            if d.conflicts:
                conflicts.append(f"- `{r['code']}` {r['name']}: {'; '.join(d.conflicts)}")
        with (OUT / f"{table}.csv").open("w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=COLUMNS, lineterminator="\n")
            w.writeheader()
            w.writerows(out)
        full = sum(1 for r in out if not r["rest"])
        common = [r for r in out if r["common"]]
        full_common = sum(1 for r in common if not r["rest"])
        report += [f"## {title}", "",
                   f"- Foods: {len(out)}; fully described: {full} ({100 * full / len(out):.0f}%)",
                   f"- Common foods: {len(common)}; fully described: {full_common}"
                   + (f" ({100 * full_common / len(common):.0f}%)" if common else ""),
                   f"- Conflicts: {len(conflicts)}", "",
                   "Most frequent unclassified phrases:", "",
                   *[f"- {n} × {p}" for p, n in words.most_common(25)], ""]
        if conflicts:
            report += ["Conflicts (two terms that can't both be true):", "", *conflicts, ""]
        print(f"{table}: {len(out)} foods, {full} fully described, {len(conflicts)} conflicts", file=sys.stderr)
    (OUT / "REPORT.md").write_text("\n".join(report))
    return 0


if __name__ == "__main__":
    sys.exit(main())
